export const MERKLE_TREE_HEIGHT = 26
export const MERKLE_TREE_ZERO_VALUE = '13957331740549083428539157647087363326246483135047439495076507042642183216086'

/** ethers v5 BigNumber (or anything numeric) -> bigint */
export const big = (x) => BigInt(BigNumber.from(x).toString())

export function createEmptyTree(height = MERKLE_TREE_HEIGHT) {
  return new MerkleTree(height, [], { hashFunction: poseidonHash2, zeroElement: MERKLE_TREE_ZERO_VALUE })
}

// ---------- contract deployment ----------

/** Poseidon hasher bytecode generated by circomlibjs (the same generator scripts/compileHasher.js uses). */
export async function deployHasher(ethers) {
  const { poseidonContract } = require('circomlibjs')
  const [signer] = await ethers.getSigners()
  const factory = new ethers.ContractFactory(poseidonContract.generateABI(2), poseidonContract.createCode(2), signer)
  const hasher = await factory.deploy()
  await hasher.waitForDeployment()
  return hasher
}

let proxyArtifact = null
/**
 * ERC1967Proxy is compiled as a dependency of contracts/shared/Proxy.sol but Hardhat 3 only writes artifacts for
 * contracts declared in project files, so read it from the build-info output.
 */
export async function getProxyFactory(ethers, signer) {
  if (!proxyArtifact) {
    const dir = path.join(ROOT, 'artifacts', 'build-info')
    for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.output.json'))) {
      const { output } = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'))
      for (const [source, contracts] of Object.entries(output.contracts || {})) {
        if (source.endsWith('/proxy/ERC1967/ERC1967Proxy.sol') && contracts.ERC1967Proxy) {
          proxyArtifact = { abi: contracts.ERC1967Proxy.abi, bytecode: '0x' + contracts.ERC1967Proxy.evm.bytecode.object }
        }
      }
    }
    if (!proxyArtifact) throw new Error('ERC1967Proxy not found in build-info; run `npx hardhat build`')
  }
  const s = signer || (await ethers.getSigners())[0]
  return new ethers.ContractFactory(proxyArtifact.abi, proxyArtifact.bytecode, s)
}

export async function deploy(ethers, contractName, ...args) {
  const Factory = await ethers.getContractFactory(contractName)
  const instance = await Factory.deploy(...args)
  await instance.waitForDeployment()
  return instance
}

/** Implementation + ERC1967 proxy initialized with initialize(max, min, admin); returns the pool bound to the proxy. */
export async function deployPoolProxy(ethers, contractName, constructorArgs, initArgs) {
  const Factory = await ethers.getContractFactory(contractName)
  const implementation = await Factory.deploy(...constructorArgs)
  await implementation.waitForDeployment()
  const initData = Factory.interface.encodeFunctionData('initialize', initArgs)
  const ERC1967Proxy = await getProxyFactory(ethers)
  const proxy = await ERC1967Proxy.deploy(await implementation.getAddress(), initData)
  await proxy.waitForDeployment()
  return { pool: Factory.attach(await proxy.getAddress()), implementation, Factory }
}

// ---------- proofs (same logic the suite always used) ----------

export async function getProof({ inputs, outputs, tree, extAmount, fee, recipient, feeRecipient, encryptionKey }) {
  const inputMerklePathIndices = []
  const inputMerklePathElements = []

  for (const input of inputs) {
    if (input.amount.gt(0)) {
      input.index = tree.indexOf(toFixedHex(input.getCommitment()))
      if (input.index < 0) {
        throw new Error(`Input commitment ${toFixedHex(input.getCommitment())} was not found`)
      }
      inputMerklePathIndices.push(input.index)
      inputMerklePathElements.push(tree.path(input.index).pathElements)
    } else {
      inputMerklePathIndices.push(0)
      inputMerklePathElements.push(new Array(MERKLE_TREE_HEIGHT).fill(0))
    }
  }

  let nextIndex = tree._layers[0].length
  for (const output of outputs) {
    output.index = nextIndex++
  }

  const extData = {
    recipient: toFixedHex(recipient, 20),
    extAmount: toFixedHex(extAmount),
    feeRecipient: toFixedHex(feeRecipient, 20),
    fee: toFixedHex(fee),
    encryptedOutput1: outputs[0].encrypt(encryptionKey),
    encryptedOutput2: outputs[1].encrypt(encryptionKey),
  }

  const extDataHash = getExtDataHash(extData)
  const input = {
    root: toFixedHex(tree.root),
    inputNullifier: inputs.map((x) => x.getNullifier().toString()),
    outputCommitment: outputs.map((x) => x.getCommitment().toString()),
    publicAmount: BigNumber.from(extAmount).sub(fee).add(FIELD_SIZE).mod(FIELD_SIZE).toString(),
    extDataHash: extDataHash.toString(),
    mintAddress: inputs[0].mintAddress.toString(),
    inAmount: inputs.map((x) => x.amount.toString()),
    inPrivateKey: inputs.map((x) => x.keypair.privkey.toString()),
    inBlinding: inputs.map((x) => x.blinding.toString()),
    inPathIndices: inputMerklePathIndices,
    inPathElements: inputMerklePathElements,
    outAmount: outputs.map((x) => x.amount.toString()),
    outBlinding: outputs.map((x) => x.blinding.toString()),
    outPubkey: outputs.map((x) => x.keypair.pubkey.toString()),
  }

  const { pA, pB, pC } = await prove(input, path.join(ROOT, `build/circuits/transaction${inputs.length}`))

  const args = {
    pA,
    pB,
    pC,
    root: toFixedHex(input.root),
    inputNullifiers: inputs.map((x) => toFixedHex(x.getNullifier())),
    outputCommitments: outputs.map((x) => toFixedHex(x.getCommitment())),
    publicAmount: toFixedHex(input.publicAmount),
    extDataHash: toFixedHex(extDataHash),
  }

  return { extData, args, outputs }
}

export async function prepareTransaction({ tree, inputs = [], outputs = [], fee = 0, recipient = 0, feeRecipient = 0, encryptionKey }) {
  if (inputs.length > 2 || outputs.length > 2) {
    throw new Error('Incorrect inputs/outputs count')
  }
  while (inputs.length < 2) {
    inputs.push(new Utxo())
  }
  while (outputs.length < 2) {
    outputs.push(new Utxo())
  }
  fee = BigNumber.from(fee)

  const extAmount = fee
    .add(outputs.reduce((sum, x) => sum.add(x.amount), BigNumber.from(0)))
    .sub(inputs.reduce((sum, x) => sum.add(x.amount), BigNumber.from(0)))

  const { args, extData, outputs: paddedOutputs } = await getProof({
    inputs, outputs, tree, extAmount, fee, recipient, feeRecipient, encryptionKey,
  })

  return { args, extData, outputs: paddedOutputs }
}

